#!/usr/bin/env python3
"""Measure whether over-spraying now costs anything in the grain domain.

Runs a no-spray baseline, an indiscriminate spray-everything policy, and a
precise thresholded policy over many seeds, under the coupled phase-1 ecology
and (with ``--legacy-ecology``) under the pre-change uncoupled dynamics, so the
before and after sides of the resurgence claim come from the same harness.

The spray policies read field densities directly: they are domain policies, not
detectors, and the numbers here are not detection claims. They answer only
whether the domain prices spray decisions at all.

Outputs `docs/grain_resurgence.json` and `docs/grain_resurgence.md`.
"""

from __future__ import annotations

import argparse
import json
import re
from collections.abc import Sequence
from pathlib import Path
from typing import Any

from grain_guard.analysis.fleet_options import (
    add_sprayer_fleet_arguments,
    sprayer_fleet_config_from_args,
)
from grain_guard.analysis.resurgence import (
    DEFAULT_SPRAY_INTERVAL,
    DEFAULT_SPRAY_THRESHOLD,
    SPRAY_POLICIES,
    run_resurgence_experiment,
)

DEFAULT_SEEDS = tuple(range(1000, 1021))
DEFAULT_STEPS = 400
JSON_ARTIFACT_NAME = "grain_resurgence.json"
REPORT_ARTIFACT_NAME = "grain_resurgence.md"
DEFAULT_OUT_DIR = "docs"

SAFE_OUTPUT_DIR = re.compile(r"[A-Za-z0-9_-]+(?:/[A-Za-z0-9_-]+)*")
"""Relative directory names accepted for output: no dots, no other separators."""

_POLICY_ROWS: tuple[tuple[str, str, str], ...] = (
    ("Spray applications", "mean_sprays", "{:.0f}"),
    ("Spray applications denied (budget or tank)", "mean_denied_sprays", "{:.0f}"),
    ("Spot applications granted by fleet", "mean_spot_granted", "{:.0f}"),
    ("Spot requests refused: empty tank", "mean_spot_denied_empty", "{:.0f}"),
    ("Spot requests refused: refilling", "mean_spot_denied_refilling", "{:.0f}"),
    ("Spot requests refused: beat spent", "mean_spot_denied_worked_out", "{:.0f}"),
    ("Spot fulfillment share", "mean_spot_fulfilled_share", "{:.4f}"),
    ("Tank refills", "mean_refills", "{:.0f}"),
    ("Liters applied", "mean_liters_applied", "{:.1f}"),
    ("Primary pest density", "mean_primary_density", "{:.1f}"),
    ("Secondary pest density", "mean_secondary_density", "{:.1f}"),
    ("Total pest density", "mean_total_density", "{:.1f}"),
    ("Primary pest-days (per-step mean)", "mean_primary_pest_days", "{:.1f}"),
    ("Secondary pest-days (per-step mean)", "mean_secondary_pest_days", "{:.1f}"),
    ("Total pest-days (per-step mean)", "mean_total_pest_days", "{:.1f}"),
    ("Peak total density", "mean_peak_total_density", "{:.1f}"),
    ("Natural-enemy density", "mean_beneficial_density", "{:.1f}"),
    ("Mean crop health", "mean_crop_health", "{:.4f}"),
    ("Yield potential", "mean_yield_potential", "{:.4f}"),
)


def safe_output_dir(raw_path: str) -> Path:
    """Resolve an output directory under the repository without traversal."""
    if not SAFE_OUTPUT_DIR.fullmatch(raw_path):
        raise ValueError(
            "out_dir must be a relative directory of letters, digits, '_', '-' and '/'"
        )
    return Path(__file__).resolve().parents[1] / raw_path


def _fmt(value: object, spec: str = "{:.4f}") -> str:
    if value is None:
        return "n/a"
    if isinstance(value, bool):
        return "yes" if value else "no"
    if isinstance(value, (int, float)):
        return spec.format(value)
    return str(value)


def markdown_report(results: dict[str, Any]) -> str:
    """Render the resurgence comparison as a Markdown table."""
    config = results["configuration"]
    verdict = results["verdict"]
    policies = results["policies"]
    lines = [
        "# Resurgence sanity experiment: grain domain",
        "",
        "Generated by `scripts/run_resurgence_experiment.py`.",
        "",
        f"- Seeds: `{len(config['seeds'])}` (`{min(config['seeds'])}`-`{max(config['seeds'])}`)",
        f"- Steps per run: `{config['steps']}`",
        f"- Coupled ecology enabled: `{config['ecology_enabled']}`",
        f"- Spray interval: `{config['spray_interval']}` steps,"
        f" efficacy `{config['spray_efficacy']}`,"
        f" precise threshold `{config['spray_threshold']}`",
        f"- Per-Tot spray tanks: `{config.get('sprayer_fleet')}`",
        f"- Global spray-budget capacity: `{config.get('spray_budget_capacity')}`",
        "",
        "## Verdict",
        "",
        f"- Indiscriminate minus precise yield potential:"
        f" `{_fmt(verdict['indiscriminate_minus_precise_yield'], '{:+.4f}')}`",
        f"- Indiscriminate minus no-spray yield potential:"
        f" `{_fmt(verdict['indiscriminate_minus_no_spray_yield'], '{:+.4f}')}`",
        f"- Indiscriminate minus precise secondary pest-days:"
        f" `{_fmt(verdict['indiscriminate_minus_precise_secondary_pest_days'], '{:+.1f}')}`",
        f"- Indiscriminate minus precise total pest-days:"
        f" `{_fmt(verdict['indiscriminate_minus_precise_pest_days'], '{:+.1f}')}`",
        f"- Indiscriminate minus precise final pest density:"
        f" `{_fmt(verdict['indiscriminate_minus_precise_density'], '{:+.1f}')}`",
        f"- Indiscriminate minus no-spray final pest density:"
        f" `{_fmt(verdict['indiscriminate_minus_no_spray_density'], '{:+.1f}')}`",
        f"- **Resurgence: `{_fmt(verdict['resurgence'])}`**",
        "",
        "## Policies",
        "",
    ]
    header = "| Metric | " + " | ".join(f"`{policy['policy']}`" for policy in policies) + " |"
    lines.append(header)
    lines.append("|" + "---|" * (len(policies) + 1))
    for label, key, spec in _POLICY_ROWS:
        cells = " | ".join(f"`{_fmt(policy.get(key), spec)}`" for policy in policies)
        lines.append(f"| {label} | {cells} |")
    lines.extend(
        [
            "",
            "## Method notes",
            "",
            "- Spray policies read field densities directly. They are domain policies, not",
            "  detectors: this experiment asks whether the domain prices spray decisions,",
            "  not how well anything detects.",
            "- `--legacy-ecology` disables the phase-1 coupling (broad-spectrum mortality on",
            "  natural enemies, predation in every cell, slow recolonization, secondary pest,",
            "  abiotic look-alikes) and reproduces the pre-change dynamics for the before side.",
            "- With `--sprayer-fleet`, thresholded spraying draws on finite drone tanks with",
            "  refill travel and downtime, while a whole-field pass is served by the boom",
            "  sprayer: targeting is scarce, total pesticide load is not capped, so the",
            "  ecological penalty for over-spraying is left intact.",
            "- Resurgence counts only when the indiscriminate policy ends with lower yield",
            "  than the precise policy and more final pests than not spraying. Requiring both",
            "  prevents crop collapse from masquerading as pest control: yield integrates the",
            "  monotone damage while the no-spray comparison establishes a density rebound.",
            "",
        ]
    )
    return "\n".join(lines)


def write_artifacts(results: dict[str, Any], out_dir: Path) -> tuple[Path, Path]:
    """Write the JSON and Markdown artifacts into ``out_dir``."""
    json_path = out_dir / JSON_ARTIFACT_NAME
    report_path = out_dir / REPORT_ARTIFACT_NAME
    json_path.write_text(json.dumps(results, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    report_path.write_text(markdown_report(results), encoding="utf-8")
    return json_path, report_path


def _parse_args(argv: Sequence[str] | None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--seeds", type=int, nargs="*", default=list(DEFAULT_SEEDS))
    parser.add_argument("--steps", type=int, default=DEFAULT_STEPS)
    parser.add_argument("--spray-interval", type=int, default=DEFAULT_SPRAY_INTERVAL)
    parser.add_argument("--spray-threshold", type=float, default=DEFAULT_SPRAY_THRESHOLD)
    parser.add_argument(
        "--policies",
        nargs="+",
        choices=SPRAY_POLICIES,
        default=list(SPRAY_POLICIES),
    )
    parser.add_argument(
        "--pest-damage-lag",
        type=int,
        default=None,
        help=(
            "Steps between pest injury being committed and becoming visible. "
            "Omit for the domain default; pass 0 for the pre-lag before measurement."
        ),
    )
    parser.add_argument(
        "--spray-budget-capacity",
        type=int,
        default=None,
        help=(
            "Maximum spray applications per budget interval. Omit for the unlimited "
            "capacity earlier phases were measured under."
        ),
    )
    parser.add_argument(
        "--spray-budget-interval",
        type=int,
        default=7,
        help="Steps per spray-budget interval; only used with --spray-budget-capacity.",
    )
    add_sprayer_fleet_arguments(parser)
    parser.add_argument(
        "--legacy-ecology",
        action="store_true",
        help="Disable phase-1 ecological coupling to reproduce the pre-change domain.",
    )
    parser.add_argument(
        "--out-dir",
        default=DEFAULT_OUT_DIR,
        help="Output directory relative to the repository root, e.g. docs.",
    )
    return parser.parse_args(argv)


def main(argv: Sequence[str] | None = None) -> int:
    """Run the resurgence comparison and write both artifacts."""
    args = _parse_args(argv)
    out_dir = safe_output_dir(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    results = run_resurgence_experiment(
        args.seeds,
        steps=args.steps,
        ecology_enabled=not args.legacy_ecology,
        spray_interval=args.spray_interval,
        spray_threshold=args.spray_threshold,
        policies=args.policies,
        pest_damage_visibility_lag_steps=args.pest_damage_lag,
        spray_budget_capacity=args.spray_budget_capacity,
        spray_budget_interval_steps=args.spray_budget_interval,
        sprayer_fleet_config=sprayer_fleet_config_from_args(args),
    )
    json_path, report_path = write_artifacts(results, out_dir)
    verdict = results["verdict"]
    print(f"resurgence: {_fmt(verdict['resurgence'])}")
    print(
        "indiscriminate minus precise yield: "
        f"{_fmt(verdict['indiscriminate_minus_precise_yield'], '{:+.4f}')}"
    )
    print(f"wrote {json_path} and {report_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
